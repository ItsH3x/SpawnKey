"""Executable shell script generator for SpawnKey dropdown profiles."""

from __future__ import annotations

import os
from pathlib import Path
import shlex
import sys

from spawnkey.core.models import DropdownProfile
from spawnkey.core.storage import AppPaths


def _default_src_root() -> Path:
    # .../src/spawnkey/core/script_gen.py -> .../src
    return Path(__file__).resolve().parents[2]


class ScriptGenerator:
    """Create, inspect, and cleanly remove per-dropdown executable wrapper scripts."""

    def __init__(
        self,
        paths: AppPaths | None = None,
        *,
        python_executable: str | None = None,
        src_root: Path | None = None,
    ) -> None:
        self.paths = paths or AppPaths.from_env()
        self.python_executable = python_executable or sys.executable or "python3"
        self.src_root = src_root or _default_src_root()

    def script_path(self, profile_id: str) -> Path:
        return self.paths.scripts_dir / f"{profile_id}.sh"

    def render_script(self, profile: DropdownProfile) -> str:
        quoted_id = shlex.quote(profile.id)
        quoted_python = shlex.quote(self.python_executable)
        quoted_src = shlex.quote(str(self.src_root))

        lines = [
            "#!/usr/bin/env bash",
            "# Generated by SpawnKey — do not edit manually if managed by the app.",
            f"# Profile: {profile.name} ({profile.id})",
            f"# Mode: {profile.mode.value} | Animation: {profile.animation_type.value} ({profile.direction.value})",
            "set -euo pipefail",
            "",
            "if command -v spawnkey >/dev/null 2>&1; then",
            f"    exec spawnkey run {quoted_id} \"$@\"",
            "fi",
            "",
            f"export PYTHONPATH={quoted_src}${{PYTHONPATH:+:$PYTHONPATH}}",
            f"exec {quoted_python} -m spawnkey run {quoted_id} \"$@\"",
            "",
        ]
        return "\n".join(lines)

    def generate(self, profile: DropdownProfile) -> Path:
        target = self.script_path(profile.id)
        target.parent.mkdir(parents=True, exist_ok=True)
        content = self.render_script(profile)
        target.write_text(content, encoding="utf-8")
        os.chmod(target, 0o755)
        profile.script_path = str(target)
        return target

    def remove(self, profile_id: str) -> bool:
        target = self.script_path(profile_id)
        if not target.exists():
            return False
        target.unlink()
        return True

    def list_scripts(self) -> list[Path]:
        if not self.paths.scripts_dir.exists():
            return []
        return sorted(self.paths.scripts_dir.glob("*.sh"))
